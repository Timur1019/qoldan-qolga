export function categoryIconName(code, fallback = 'folder2-open', parentCode = '') {
  if (!code) return fallback
  let current = code
  const seen = new Set()
  while (current && !seen.has(current)) {
    const icon = CATEGORY_ICONS[current]
    if (icon) return icon
    seen.add(current)
    current = CATEGORY_PARENTS[current] || (current === code ? parentCode : '') || ''
  }
  if (parentCode && CATEGORY_ICONS[parentCode]) return CATEGORY_ICONS[parentCode]
  return fallback
}

